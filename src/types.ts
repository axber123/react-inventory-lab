/* ============================================================
 * 【本文件知识点】TypeScript 的 type：给数据"定型"
 *
 * 先说人话：TS = JavaScript + 类型检查。
 * JS 的问题是什么都装得下，写错字要到运行时才发现，比如：
 *
 *   const item = { matnr: "100001", qty: 10 }  // 字段名手滑写错了
 *   item.qyt                                   // 页面空白，却不报错！
 *
 * 有了类型标注之后：
 *   - 编辑器敲 item. 会自动提示所有可用字段
 *   - 字段写错 / 类型用错（把数字当字符串用）当场画红线
 *   - 跑 npm run typecheck 能把这类错误全查出来
 *
 * ⚠️ TS 只在"写代码阶段"帮忙，最终跑的还是普通 JS。
 * ============================================================ */

/**
 * 一条库存物料的数据结构。
 * 项目的 api 层、hook、多个页面都要用到它 —— 所以放在独立文件里共享。
 */
export type Inventory = {
  matnr: string; // 物料编号（material number 的缩写，ERP 系统常用词）
  name: string; // 物料名称
  quantity: number; // 当前库存数量
};
